import { expect, test } from '@playwright/test'

test('inspecciona la cola, retrocede, reproduce, pausa y reinicia', async ({ page }) => {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Visualizador AC-3' })).toBeVisible()
  await expect(page.getByRole('figure', { name: 'Tablero de ajedrez de ocho por ocho' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Iniciar', exact: true }).click()
  await expect(page.getByText('Iniciar la búsqueda', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Siguiente paso', exact: true }).click()
  await expect(page.getByText('Inicializar la cola', { exact: true })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Arcos pendientes en orden' }).getByRole('listitem')).toHaveCount(56)
  await page.getByRole('button', { name: 'Paso anterior', exact: true }).click()
  await expect(page.getByText('Iniciar la búsqueda', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Velocidad', exact: true }).selectOption('25')
  await page.getByRole('button', { name: 'Reproducir' }).click()
  await expect(page.getByRole('button', { name: 'Pausar' })).toBeVisible()
  await page.getByRole('button', { name: 'Pausar' }).click()
  await expect(page.getByRole('button', { name: 'Reproducir' })).toBeVisible()
  await page.getByRole('button', { name: 'Reproducir' }).click()
  await expect(page.getByRole('button', { name: 'Pausar' })).toBeVisible()
  await page.getByRole('button', { name: 'Pausar' }).click()
  await page.getByRole('button', { name: 'Reiniciar ejecución' }).click()
  await expect(page.locator('.trace-workspace:visible').getByText('Listo para comenzar', { exact: true })).toBeVisible()
})

test('el laboratorio detecta ataques y deshace asignaciones sin podar antes de AC-3', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Laboratorio', exact: true }).click()
  const lab = page.locator('.trace-workspace:visible')
  await page.getByRole('button', { name: 'A8, fila 0', exact: true }).click()
  await expect(lab.getByLabel('Q1, 1, disponible')).toBeVisible()
  await page.getByRole('button', { name: 'B7, fila 1', exact: true }).click()
  await page.getByRole('button', { name: 'Verificar', exact: true }).click()
  await expect(page.getByRole('status').getByText('Q0 y Q1 comparten diagonal.')).toBeVisible()
  await page.getByRole('button', { name: 'Ejecutar AC-3' }).click()
  await page.getByRole('button', { name: 'Siguiente evento importante' }).click()
  await expect(page.getByText('Eliminar un valor', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Siguiente evento importante' }).click()
  await expect(page.getByText('Detectar contradicción', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Deshacer' }).click()
  await expect(lab.getByLabel('Q0, 0, asignado')).toBeVisible()
  await expect(lab.getByLabel('Q1, 1, disponible')).toBeVisible()
})

test('resuelve en el worker y permite explorar, agrupar y comparar soluciones', async ({ page }) => {
  const errors: Error[] = []
  page.on('pageerror', error => errors.push(error))
  await page.goto('./')
  await page.getByRole('button', { name: 'Resolución rápida' }).click()
  await page.getByRole('button', { name: 'Resolver', exact: true }).click()
  await expect(page.getByText('Búsqueda completa · 92 soluciones verificadas.')).toBeVisible()
  await page.getByRole('link', { name: 'Explorar soluciones' }).click()
  await expect(page.getByRole('heading', { name: 'Explorador de soluciones' })).toBeVisible()
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Solución 2', exact: true })).toBeVisible()
  await page.getByLabel('Número', { exact: true }).fill('93')
  await page.getByRole('button', { name: 'Ir', exact: true }).click()
  await expect(page.getByRole('status').getByText('Introduce un número entero entre 1 y 92.')).toBeVisible()
  await page.getByLabel('Agrupar por clase fundamental').check()
  await expect(page.getByRole('heading', { name: 'Clase fundamental 1', exact: true })).toBeVisible()
  await expect(page.getByText('1 / 12', { exact: true })).toBeVisible()
  await page.getByLabel('Transformación').selectOption('1')
  await page.getByLabel('Comparar con otra solución').check()
  await expect(page.getByText(/de 8 columnas cambian/)).toBeVisible()
  expect(errors).toEqual([])
})

