test('sitio móvil sin desbordamiento, navegación, tema y reducción de movimiento', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('./')
  await expect(page.getByRole('button', { name: 'Iniciar', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Iniciar', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.getByRole('link', { name: 'Aprender', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aprender AC-3' })).toBeVisible()
  await page.getByRole('button', { name: 'Abrir Laboratorio' }).click()
  await expect(page.getByRole('heading', { name: 'Asignaciones manuales' })).toBeVisible()
  await page.getByRole('button', { name: 'Activar tema claro' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByLabel('Reducir movimiento').check()
  await expect(page.locator('html')).toHaveAttribute('data-motion', 'reduce')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
